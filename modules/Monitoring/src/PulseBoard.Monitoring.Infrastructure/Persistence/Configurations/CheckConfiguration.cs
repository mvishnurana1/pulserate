using Microsoft.EntityFrameworkCore;
using Microsoft.EntityFrameworkCore.Metadata.Builders;
using PulseBoard.Monitoring.Domain.Checks;

namespace PulseBoard.Monitoring.Infrastructure.Persistence.Configurations;

internal sealed class CheckConfiguration : IEntityTypeConfiguration<Check>
{
    public void Configure(EntityTypeBuilder<Check> builder)
    {
        builder.ToTable("Checks");

        builder.HasKey(c => c.Id);
        builder.Property(c => c.Id).ValueGeneratedNever(); // UUIDv7 generated by the domain.

        builder.Property(c => c.Name)
            .HasMaxLength(Check.NameMaxLength)
            .IsRequired();

        builder.Property(c => c.Url)
            .HasConversion(url => url.AbsoluteUri, value => new Uri(value))
            .HasMaxLength(Check.UrlMaxLength)
            .IsRequired();

        builder.Property(c => c.Status)
            .HasConversion<string>()
            .HasMaxLength(20);

        // Optimistic concurrency using Postgres' built-in xmin system column,
        // so two people editing the same check can't silently overwrite each other.
        builder.Property<uint>("Version").IsRowVersion();

        // The scheduler asks "which checks are due?" every minute.
        builder.HasIndex(c => c.NextCheckAt);

        builder.Ignore(c => c.DomainEvents);
    }
}
